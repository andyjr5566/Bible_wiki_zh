"""Freeze relief derived from collected uint16 DEM; no network or production data edits.
Run from the site: python -I tools/build-review-terrain.py
"""
from pathlib import Path
import hashlib
import io
import json
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def relief(name, exaggeration):
    source = ROOT / 'collect' / 'dem'
    meta = json.loads((source / f'{name}_meta.json').read_text(encoding='utf-8'))
    height_path = source / f'{name}_height.png'
    # Resize float elevations before computing normals, preserving the signed heights.
    elevation = np.asarray(Image.open(height_path), dtype=np.float32) - meta['elevation_offset']
    original_h, original_w = elevation.shape
    width = min(1200, original_w)
    height = round(original_h * width / original_w)
    elevation = np.asarray(Image.fromarray(elevation).resize((width, height), Image.Resampling.BILINEAR))
    meters = meta['meters_per_pixel_at_center_lat'] * original_w / width
    dy, dx = np.gradient(elevation, meters)
    nx, ny = -dx * exaggeration, dy * exaggeration
    length = np.sqrt(nx * nx + ny * ny + 1)
    shade = np.clip((nx * -0.5 + ny * -0.5 + .707) / length, -.3, 1)
    # Limestone, olive hills and parchment valleys; water is masked from geo vectors in the UI.
    levels = [-600, -200, 0, 200, 500, 850, 1400]
    colors = np.array([[214,194,147], [218,201,159], [225,211,174], [211,202,158], [172,180,133], [143,160,119], [212,207,177]])
    image = np.stack([np.interp(elevation, levels, colors[:, c]) for c in range(3)], axis=-1)
    image *= (.78 + .32 * shade[..., None])
    image = np.clip(image, 0, 255).astype(np.uint8)
    output = io.BytesIO()
    Image.fromarray(image).save(output, format='WEBP', quality=88, method=6)
    assets = ROOT / 'src' / 'assets' / 'dem'
    (assets / f'review-{name}.webp').write_bytes(output.getvalue())
    return {
        'width': width, 'height': height,
        'sourceWidth': original_w, 'sourceHeight': original_h,
        'zoom': meta['zoom'], 'origin': meta['origin_world_px'],
        'bbox': meta['actual_bbox'],
        'heightSha256': hashlib.sha256(height_path.read_bytes()).hexdigest(),
    }


payload = {'shechem': relief('shechem_valley', 2.0), 'canaan': relief('canaan', 3.5)}
target = ROOT / 'src' / 'ui' / 'review-terrain.ts'
imports = "import shechem from '../assets/dem/review-shechem_valley.webp';\nimport canaan from '../assets/dem/review-canaan.webp';\n"
entries = ','.join(f'{key}:{{...{json.dumps(value, separators=(",", ":"))},image:{key}}}' for key, value in payload.items())
target.write_text('// Generated by tools/build-review-terrain.py from collected DEM.\n' + imports + 'export const reviewTerrain = {' + entries + '} as const;\n', encoding='utf-8')
print(f'{target.name}: {target.stat().st_size:,} bytes; two DEM SHA-256 receipts embedded')
