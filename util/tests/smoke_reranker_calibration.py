    N_top1 = list(sim_neg_top1) and []          # 重排分數另存
    for i, (n, ty, ev, gold) in enumerate(GOLD):
        deep = hits_of[i][:RERANK_N]
        def run(items):
            docs = [entry_rerank_document(ti, e) for ti, s, e in items]
            rr = rerank_documents(queries[i], docs, task="rerank")
            return [(items[x["index"]][0], x["relevance_score"]) for x in rr]
        if gold:
            ranked = run(deep)
            names = [a for a, _ in ranked]; scores = [b for _, b in ranked]
            P_top1.append(scores[0])
            P_margin.append(scores[0] - scores[1] if len(scores) > 1 else 0.0)
            if gold in names:
                k = names.index(gold); P_gold.append(scores[k]); P_rank.append(k + 1)
            masked = [x for x in deep if x[0] != gold]
            if masked: N_top1.append(run(masked)[0][1])
        else:
            N_top1.append(run(deep)[0][1])

    print(f"  正例 gold 分數（{len(P_gold)}）：{band(P_gold)}")
    print(f"  負例 top-1 分數（{len(N_top1)}）：{band(N_top1)}")
    print(f"  gold 被重排到 top-1：{sum(1 for r in P_rank if r == 1)}/{len(P_rank)}"
          f"（檢索階段 {sum(1 for r in ranks if r == 1)}/{len(pos)}）")
    print(f"  Top1-Top2 margin：{band(P_margin)}")

    # ---------- 門檻掃描：這才是 score_high / score_low 該看的東西 ----------
    print()
    print("[門檻掃描] score_high＝自動判「用既有條目」；score_low＝自動判「建新條目」")
    print("  score_high  正例命中   負例誤判(不該說有卻說有)")
    for thr in (0.70, 0.80, 0.90, 0.95, 0.99):
        tp = sum(1 for s in P_gold if s >= thr)
        fp = sum(1 for s in N_top1 if s >= thr)
        print(f"    {thr:<10.2f} {tp:>3}/{len(P_gold)} ({tp/len(P_gold):.0%})   {fp:>3}/{len(N_top1)} ({fp/len(N_top1):.0%})")
    print("  score_low   負例命中   正例誤判(該說有卻說沒有)")
    for thr in (0.20, 0.30, 0.40, 0.50, 0.60):
        tn = sum(1 for s in N_top1 if s < thr)
        fn = sum(1 for s in P_gold if s < thr)
        print(f"    {thr:<10.2f} {tn:>3}/{len(N_top1)} ({tn/len(N_top1):.0%})   {fn:>3}/{len(P_gold)} ({fn/len(P_gold):.0%})")

